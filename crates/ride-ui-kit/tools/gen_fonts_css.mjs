// Regenerates assets/fonts.css (embedded @font-face rules with base64 data URIs) from
// assets/fonts/*.woff2:   node crates/ride-ui-kit/tools/gen_fonts_css.mjs
// A unit test in src/lib.rs fails when fonts.css and the woff2 files drift apart.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'assets');
const faces = [
  ['Barlow', 400, 'Barlow-Regular'],
  ['Barlow', 500, 'Barlow-Medium'],
  ['Barlow', 600, 'Barlow-SemiBold'],
  ['Barlow Condensed', 500, 'BarlowCondensed-Medium'],
  ['Barlow Condensed', 600, 'BarlowCondensed-SemiBold'],
  ['Barlow Condensed', 700, 'BarlowCondensed-Bold'],
];
let out = `/* Barlow and Barlow Condensed, (c) 2017 The Barlow Project Authors (https://github.com/jpt/barlow),
   SIL Open Font License 1.1 (assets/fonts/OFL.txt). Subset to Basic Latin, Latin-1 and Latin
   Extended-A (U+0100-017F: Hungarian o-double-acute / u-double-acute) plus common punctuation and
   maths signs, converted to WOFF2 and embedded as data URIs so the app works offline.
   GENERATED by tools/gen_fonts_css.mjs - do not edit by hand. */\n`;
for (const [family, weight, file] of faces) {
  const b64 = fs.readFileSync(path.join(root, 'fonts', `${file}.woff2`)).toString('base64');
  out += `@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:block;src:url(data:font/woff2;base64,${b64}) format("woff2");}\n`;
}
fs.writeFileSync(path.join(root, 'fonts.css'), out);
console.log('fonts.css', out.length, 'bytes');
