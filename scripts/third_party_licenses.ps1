<#
.SYNOPSIS
  Generates THIRD_PARTY_LICENSES.md from `cargo metadata`.

.DESCRIPTION
  Lists every crates.io package the workspace resolves to, with its version, licence
  expression and repository. Using `cargo metadata` (instead of scraping the registry cache)
  also covers dependencies that are not built on this platform, so every entry carries the
  licence published in the crates.io index. Workspace/path crates are skipped; vendored or
  ported source is described in NOTICE.md instead.

  The output is sorted (name, then version), so regenerating only changes it when the
  dependency graph changes.

.EXAMPLE
  pwsh -File .\scripts\third_party_licenses.ps1
#>
[CmdletBinding()]
param(
    [string]$Out = ''
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
if (-not $Out) { $Out = Join-Path $root 'THIRD_PARTY_LICENSES.md' }

$manifest = Join-Path $root 'Cargo.toml'
$tmp = [System.IO.Path]::GetTempFileName()
try {
    # Through cmd so that cargo's progress lines on stderr do not trip PowerShell 5's
    # native-command error handling (and never mix into the JSON).
    $line = 'cargo metadata --format-version 1 --locked --manifest-path "{0}" > "{1}" 2>NUL' -f $manifest, $tmp
    & cmd.exe /c $line
    if ($LASTEXITCODE -ne 0) { throw "cargo metadata failed (exit $LASTEXITCODE)" }
    $json = Get-Content -LiteralPath $tmp -Raw -Encoding UTF8
}
finally {
    Remove-Item -LiteralPath $tmp -Force -ErrorAction SilentlyContinue
}
if (-not $json) { throw 'cargo metadata produced no output' }
$meta = $json | ConvertFrom-Json

$thirdParty = @($meta.packages | Where-Object { $_.source -and $_.source -like 'registry+*' })
$sorted = $thirdParty | Sort-Object name, version
$count = @($sorted).Count
$declared = @($sorted | Where-Object { $_.license }).Count
$undeclared = $count - $declared

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# Third-party licences')
[void]$sb.AppendLine()
[void]$sb.AppendLine('Every crates.io package the workspace resolves to, generated by')
[void]$sb.AppendLine('`scripts/third_party_licenses.ps1` from `cargo metadata`. Licences that were not')
[void]$sb.AppendLine('declared in the crate metadata are marked; the map and route data sources are')
[void]$sb.AppendLine('attributed in the README Licenc section and in the app about dialog, and vendored')
[void]$sb.AppendLine('or ported source files are described in [`NOTICE.md`](NOTICE.md).')
[void]$sb.AppendLine()
[void]$sb.AppendLine("Packages: **$count**. Without a declared licence field: **$undeclared**.")
[void]$sb.AppendLine()
[void]$sb.AppendLine('| Crate | Version | Licence | Repository |')
[void]$sb.AppendLine('|---|---|---|---|')
foreach ($p in $sorted) {
    $lic = if ($p.license) { $p.license -replace '\|', '\|' } else { '*not declared*' }
    $repo = if ($p.repository) { "<$($p.repository)>" } else { '' }
    [void]$sb.AppendLine("| $($p.name) | $($p.version) | $lic | $repo |")
}
[void]$sb.AppendLine()
[void]$sb.AppendLine('The project itself is `MIT OR Apache-2.0`; see [`LICENSE-MIT`](LICENSE-MIT) and')
[void]$sb.AppendLine('[`LICENSE-APACHE`](LICENSE-APACHE).')

$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($Out, $sb.ToString(), $utf8)
Write-Host "Wrote $Out ($count packages, $undeclared without a declared licence)."
